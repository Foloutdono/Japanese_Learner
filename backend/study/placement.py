# ── 実力診断 — the onboarding placement test ──────────────────────
# Since plan 221 the test CLIMBS (the owner's call): it asks at N5, and
# while the learner is good enough it goes on to the next level, as far
# as N1; the first level they do not clear is where they board. Each
# level asks until its verdict is certain -- three right in a row, or
# four right, clears it; a second miss ends it -- so at most five
# questions a level, and a learner who knows nothing is done in two.
# level_block() and walk() below are that test; the fixed paper of
# twelve (PLACEMENT_LADDER, build_placement_paper, recommend_level)
# still answers the two routes a client built before it calls.
#
# The questions are built entirely from
# data this project already owns and scored by study/exam_scoring.py's
# pure functions. No LLM, no network, no database: a paper builds in
# milliseconds, which is the whole reason this module exists instead of
# a 21st entry in routes/exams.py's EXAM_GENERATORS — that pipeline's
# papers are one-level, globally immutable, FK'd by attempts, and
# generated by an LLM behind a claim-lock job table that answers 202
# until a background thread finishes. Minutes of "generating…" is a
# fatal first-run experience; placement answers synchronously.
#
# Statelessness is the design: POST /placement returns {seed,
# questions-without-answers}; POST /placement/score regenerates the
# byte-identical paper FROM that seed and grades against it. Nothing is
# stored, nothing expires, and a tampered seed only mis-places the
# tamperer. That contract holds because everything here is a pure
# function of (seed, import-time content data) — keep it that way. In
# particular study/mcq.py's pick_distractors is deliberately NOT used:
# it draws from the module-global `random`, which would make the
# score-time regeneration disagree with the paper the learner saw.
import random
from functools import lru_cache

from content.grammar_points_data import GRAMMAR_POINTS_BY_LEVEL
from content.grammar_sentences_data import get_sentences
from content.vocab_data import VOCAB_BY_LEVEL
from study.difficulty import LEVELS
from study.exam_gen_utils import GenerationFailed, make_choices
from study.exam_scoring import flatten_questions
from study.exam_kanji_gen import build_orthography_mondai, build_reading_mondai
from study.exam_vocab_gen import build_vocab_context_mondai
from study.grammar_match import contains_pattern, verifiable

# One entry per level, easiest first; the kinds are the question mix for
# that level's section. 3+3+2+2+2 = 12 questions. The lower levels get
# the extra item because that is where one question changes the
# recommendation the most (nearly every learner passes through them).
PLACEMENT_LADDER: list[tuple[str, list[str]]] = [
    ("N5", ["reading", "context", "grammar"]),
    ("N4", ["reading", "orthography", "grammar"]),
    ("N3", ["reading", "context"]),
    ("N2", ["orthography", "grammar"]),
    ("N1", ["reading", "context"]),
]

# A level is cleared at two thirds correct. recommend_level() walks the
# ladder and recommends the level AFTER the highest consecutively
# cleared one: you board where there is still something to learn.
_CLEAR_NUM, _CLEAR_DEN = 2, 3

_GRAMMAR_INSTRUCTIONS_JP = "つぎの　文で　つかわれている　文法を　1・2・3・4から　一つ　えらんで　ください。"


def _build_grammar_fill_mondai(spec: dict, level: str, rng: random.Random) -> dict:
    """One 'which rule is at work' item, the same shape routes/grammar.py's
    fill_in mode asks (the sentence shown INTACT — blanking the rule out
    has no unique answer, see grammar.py). Distractors are other
    verifiable same-level patterns that do NOT also appear in the
    sentence, so the item never has two defensible answers."""
    points = [
        g for g in GRAMMAR_POINTS_BY_LEVEL.get(level, [])
        if verifiable(g["pattern"]) and get_sentences(level, g["pattern"])
    ]
    for entry in rng.sample(points, len(points)):
        pattern = entry["pattern"]
        sentence = get_sentences(level, pattern)[0]
        others = [
            g["pattern"] for g in GRAMMAR_POINTS_BY_LEVEL[level]
            if g["pattern"] != pattern
            and verifiable(g["pattern"])
            and not contains_pattern(sentence["jp"], g["pattern"])
        ]
        made = make_choices(rng, pattern, others)
        if made is None:
            continue
        choices, answer_id = made
        return {
            "id": spec["id"],
            "number": spec["official_number"],
            "type": "mcq-text",
            "instructionsJp": _GRAMMAR_INSTRUCTIONS_JP,
            "instructions": "Choose the grammar pattern used in the sentence.",
            "questions": [{
                "id": f"{spec['id']}_q1",
                "number": 1,
                "promptJp": sentence["jp"],
                "choices": choices,
                "answer": answer_id,
            }],
        }
    raise GenerationFailed(f"{spec['id']}: no grammar point with a usable sentence at {level}")


def _build_one(kind: str, level: str, spec: dict, pool: list[dict],
               used_words: set, used_prompts: set, rng: random.Random) -> dict:
    if kind == "reading":
        return build_reading_mondai(spec, pool, used_words, used_prompts, rng)
    if kind == "orthography":
        return build_orthography_mondai(spec, pool, used_words, used_prompts, rng)
    if kind == "context":
        return build_vocab_context_mondai(spec, pool, used_words, used_prompts, rng, level)
    if kind == "grammar":
        return _build_grammar_fill_mondai(spec, level, rng)
    raise GenerationFailed(f"unknown placement kind {kind!r}")


def build_placement_paper(seed: int) -> dict:
    """The full 12-question paper, score_attempt-compatible. One section
    PER LEVEL (id 'N5'..'N1') — that structural choice is what makes
    score_attempt's perSection a per-level scoreboard with no changes to
    exam_scoring.py at all.

    Every (level, kind) build gets a fallback chain [kind, reading,
    orthography]: a placement must never fail because one word lacked a
    kanji-gated example sentence, and 'reading' over a full level pool
    practically cannot fail. The chain is itself replayed identically at
    score time — a failed builder is a pure function of the same seed
    and the same content data, so it fails the same way again."""
    rng = random.Random(seed)
    used_words: set = set()
    used_prompts: set = set()
    pools = {
        level: rng.sample(VOCAB_BY_LEVEL[level], len(VOCAB_BY_LEVEL[level]))
        for level, _ in PLACEMENT_LADDER
    }

    sections = []
    number = 0
    for level, kinds in PLACEMENT_LADDER:
        mondai = []
        for kind in kinds:
            number += 1
            built = None
            for attempt in (kind, "reading", "orthography"):
                spec = {"id": f"pl_{level}_{attempt}_{number}", "official_number": number, "count": 1}
                try:
                    built = _build_one(attempt, level, spec, pools[level], used_words, used_prompts, rng)
                    actual_kind = attempt
                    break
                except GenerationFailed:
                    continue
            if built is None:
                raise GenerationFailed(f"placement: every builder failed for {level}/{kind}")
            # The kind rides on each QUESTION (not the mondai) because
            # flatten_questions only carries a fixed set of mondai
            # fields through — and the frontend keys its per-kind
            # instruction line off this.
            for q in built["questions"]:
                q["kind"] = actual_kind
            mondai.append(built)
        sections.append({"id": level, "label": level, "mondai": mondai})

    return {"sections": sections}


def strip_answers(flat_questions: list[dict]) -> list[dict]:
    """What the client may see: everything but the answer key."""
    return [{k: v for k, v in q.items() if k != "answer"} for q in flat_questions]


def recommend_level(per_section: dict) -> str:
    """perSection (from score_attempt, keyed by level) → the boarding
    station. Unanswered questions are simply wrong — which is what makes
    a partial submission ('stop here, this is too hard') legal with no
    server-side session state."""
    cleared_up_to = None
    for level in LEVELS:
        stats = per_section.get(level) or {}
        total = stats.get("total", 0)
        correct = stats.get("correct", 0)
        if total and correct * _CLEAR_DEN >= total * _CLEAR_NUM:
            cleared_up_to = level
        else:
            break
    if cleared_up_to is None:
        return LEVELS[0]
    return LEVELS[min(LEVELS.index(cleared_up_to) + 1, len(LEVELS) - 1)]



# ── The climb (plan 221) ──────────────────────────────────────────
# A level's questions, in the order they are asked. The first three
# decide most levels, so they are three different kinds.
CLIMB: dict[str, list[str]] = {
    "N5": ["reading", "context", "grammar", "orthography", "reading"],
    "N4": ["reading", "grammar", "context", "orthography", "reading"],
    "N3": ["reading", "context", "grammar", "orthography", "context"],
    "N2": ["orthography", "grammar", "reading", "context", "grammar"],
    "N1": ["reading", "context", "grammar", "orthography", "reading"],
}

# A level is CLEARED by three right before any miss, or by four right;
# it is NOT cleared at the second miss. Five questions always settle it.
# Guessing clears a level about one time in forty; a learner who knows
# 60% of a level clears it about half the time, and one who knows 90%
# nineteen times in twenty -- where the old two-of-three cleared that
# 60% learner four times in five, and the level rule then marked the
# whole level known.
CLEAR_STRAIGHT = 3
CLEAR_RIGHT = 4
FAIL_WRONG = 2
PER_LEVEL = CLEAR_RIGHT + FAIL_WRONG - 1

assert all(len(kinds) == PER_LEVEL for kinds in CLIMB.values())


def judge(results: list[bool]) -> str | None:
    """A level's answers so far -> "cleared", "failed", or None while
    undecided."""
    right = sum(1 for r in results if r)
    wrong = len(results) - right
    if wrong == 0 and right >= CLEAR_STRAIGHT:
        return "cleared"
    if right >= CLEAR_RIGHT:
        return "cleared"
    if wrong >= FAIL_WRONG:
        return "failed"
    return None


@lru_cache(maxsize=256)
def _climb_block(seed: int, level: str) -> tuple[tuple[dict, ...], frozenset, frozenset]:
    """The level's questions for this seed, and the words and prompts
    used up to and including it -- so a later level never repeats one.

    Each level has a random stream of its own, so the test builds only
    the levels it reaches: a context question costs a tenth of a
    second, and the score of every answer rebuilds the test from its
    seed. Cached, since the same seed is asked again at every answer
    (learner-independent work, computed once: plan 211). A pure
    function of (seed, level, content data), like the whole paper."""
    index = LEVELS.index(level)
    if index:
        _, used_words, used_prompts = _climb_block(seed, LEVELS[index - 1])
        used_words, used_prompts = set(used_words), set(used_prompts)
    else:
        used_words, used_prompts = set(), set()
    rng = random.Random(f"{seed}:{level}")
    pool = rng.sample(VOCAB_BY_LEVEL[level], len(VOCAB_BY_LEVEL[level]))
    mondai = []
    for i, kind in enumerate(CLIMB[level]):
        number = index * PER_LEVEL + i + 1
        built = None
        for attempt in (kind, "reading", "orthography"):
            spec = {"id": f"pl_{level}_{attempt}_{number}", "official_number": number, "count": 1}
            try:
                built = _build_one(attempt, level, spec, pool, used_words, used_prompts, rng)
                actual_kind = attempt
                break
            except GenerationFailed:
                continue
        if built is None:
            raise GenerationFailed(f"placement: every builder failed for {level}/{kind}")
        for q in built["questions"]:
            q["kind"] = actual_kind
        mondai.append(built)
    questions = flatten_questions({"sections": [{"id": level, "label": level, "mondai": mondai}]})
    return tuple(questions), frozenset(used_words), frozenset(used_prompts)


def level_block(seed: int, level: str) -> list[dict]:
    """The questions the climb asks at `level`, answers included."""
    return list(_climb_block(seed, level)[0])


def walk(seed: int, answers: dict[str, str], stop: bool = False) -> dict:
    """The climb replayed from its seed over the answers given.

    Returns either the next question to ask -- {"done": False,
    "question", "level", "perLevel"} -- or the verdict -- {"done": True,
    "recommendedLevel", "perLevel", "correct", "total"}. `perLevel`
    holds each level reached: {"correct", "total", "cleared"}, cleared
    None while it is being asked. `stop` is the learner's "too hard":
    the level being asked is not cleared, and they board there.

    The learner boards at the first level they do not clear, where
    there is still something to learn; clearing N1 boards at N1, which
    has no level above. A level is asked only once the one under it is
    cleared, so an answer to a level never reached is ignored."""
    per_level: dict[str, dict] = {}
    for level in LEVELS:
        results: list[bool] = []
        verdict = None
        for q in level_block(seed, level):
            verdict = judge(results)
            if verdict:
                break
            if q["id"] not in answers:
                if stop:
                    verdict = "failed"
                    break
                per_level[level] = _tally(results, None)
                return {"done": False, "question": strip_answers([q])[0], "level": level, "perLevel": per_level}
            results.append(answers[q["id"]] == q["answer"])
        verdict = verdict or judge(results)
        per_level[level] = _tally(results, verdict == "cleared")
        if verdict != "cleared":
            return _verdict(level, per_level)
    return _verdict(LEVELS[-1], per_level)


def _tally(results: list[bool], cleared: bool | None) -> dict:
    return {"correct": sum(1 for r in results if r), "total": len(results), "cleared": cleared}


def _verdict(level: str, per_level: dict) -> dict:
    return {
        "done": True,
        "recommendedLevel": level,
        "perLevel": per_level,
        "correct": sum(t["correct"] for t in per_level.values()),
        "total": sum(t["total"] for t in per_level.values()),
    }
